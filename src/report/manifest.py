"""Keeps track of every report file: a caption per file (report_summary.md) and every key
number in one place (report_numbers.json). Steps 2 and 3 both add to the same folder."""
import json
import os
from pathlib import Path

_EXTRA_CAPTIONS = {
    "_val_predictions.csv": "{name}: every validation prediction with its word ID, writer, truth and prediction.",
    "_test_predictions.csv": "{name}: every test prediction with its word ID, writer, truth and prediction (used for the comparison).",
    "report_numbers.json": "Every key number from Steps 2-5 in one place (metrics, model size, training, data, comparison).",
    "report_summary.md": "This file: every report output with a suggested caption.",
    "manifest.json": "Internal list of files and captions used to write this summary.",
}

KINDS = {".png": "figure", ".pdf": "figure", ".csv": "table", ".tex": "table", ".json": "data", ".md": "data"}


class Report:
    def __init__(self, out_dir, step):
        self.dir = Path(out_dir); self.dir.mkdir(parents=True, exist_ok=True)
        self.step = step
        self.manifest_path = self.dir / "manifest.json"
        self.numbers_path = self.dir / "report_numbers.json"

    # -- captions
    def _manifest(self):
        return json.loads(self.manifest_path.read_text()) if self.manifest_path.exists() else {}

    def add(self, paths, caption):
        """Record the files just saved (e.g. [x.png, x.pdf]) with one suggested caption."""
        m = self._manifest()
        for p in paths:
            m[Path(p).name] = {"caption": caption, "step": self.step}
        self.manifest_path.write_text(json.dumps(m, indent=1, ensure_ascii=False))
        return paths

    # -- numbers
    def numbers(self, section=None, data=None):
        """Merge `data` into report_numbers.json under `section` (replacing that section)."""
        nums = json.loads(self.numbers_path.read_text()) if self.numbers_path.exists() else {}
        if section is not None:
            nums[section] = data
            self.numbers_path.write_text(json.dumps(nums, indent=2, ensure_ascii=False))
        return nums

    # -- summary
    def write_summary(self, future_work=None):
        m = self._manifest()
        for f in self.dir.iterdir():          # data files written outside rep.add()
            for pat, cap in _EXTRA_CAPTIONS.items():
                if f.is_file() and f.name not in m and f.name.endswith(pat):
                    who = f.name.split("_")[0]
                    m[f.name] = {"caption": cap.format(name={"crnn": "CRNN", "tesseract": "Tesseract",
                                                             "emnist": "EMNIST baseline"}.get(who, who)),
                                 "step": {"crnn": "2", "tesseract": "3", "emnist": "4"}.get(who, "2-4")}
        groups = {}
        for name, info in m.items():
            if not (self.dir / name).exists():
                continue
            stem, ext = os.path.splitext(name)
            kind = "data" if (ext == ".csv" and stem.endswith("_predictions")) else KINDS.get(ext, "data")
            groups.setdefault((kind, stem), {"exts": [], **info})["exts"].append(ext)
        lines = ["# Report outputs", "",
                 "Everything in this folder was generated by the notebooks (Step 2 = CRNN, Step 3 = Tesseract baseline, "
                 "Step 4 = EMNIST character-classifier baseline, Step 5 = webcam test set).",
                 "", "**Overleaf:** upload the folder, add `\\usepackage{booktabs}` and `\\usepackage{graphicx}` to the preamble, then",
                 "use `\\includegraphics[width=\\linewidth]{fig_name.pdf}` for figures and `\\input{table_name.tex}` for tables",
                 "(each `.tex` is a complete `table` with caption and label; edit the caption to taste).", ""]
        titles = {"figure": "## Figures (PNG 300 dpi + PDF)", "table": "## Tables (CSV + LaTeX booktabs)", "data": "## Data files"}
        for kind in ("figure", "table", "data"):
            items = sorted((s, g) for (k, s), g in groups.items() if k == kind)
            if not items:
                continue
            lines += [titles[kind], ""]
            for stem, g in items:
                files = ", ".join(f"`{stem}{e}`" for e in sorted(g["exts"]))
                lines.append(f"- {files} (step {g['step']}): {g['caption']}")
            lines.append("")
        nums = self.numbers()
        if nums:
            lines += ["## Key numbers", "", "Headline values (every number is in `report_numbers.json`):", ""]
            lines += [f"- {h}" for h in headlines(nums)] + [""]
        if future_work:
            lines += ["## Future work", ""] + [f"- {x}" for x in future_work] + [""]
        path = self.dir / "report_summary.md"
        path.write_text("\n".join(lines))
        return str(path)

    def list_files(self):
        files = sorted(p for p in self.dir.iterdir() if p.is_file())
        for p in files:
            print(f"  {p.stat().st_size / 1024:8.1f} KB  {p.name}")
        print(f"{len(files)} files in {self.dir}")
        return files


def _flatten(d, prefix=""):
    """{'test': {'cer': 0.1}} -> {'test.cer': 0.1}; skips lists and long nested blocks."""
    out = {}
    for k, v in d.items():
        if isinstance(v, dict):
            out.update(_flatten(v, f"{prefix}{k}."))
        elif isinstance(v, (int, float, str, bool)) and v is not None:
            out[f"{prefix}{k}"] = v
    return out


def _short(v):
    if isinstance(v, bool):
        return str(v)
    return f"{v:.4f}" if isinstance(v, float) else (f"{v:,}" if isinstance(v, int) else str(v))


def headlines(nums):
    """Short, readable list of the numbers most likely to go into the report text."""
    out, p = [], lambda x: f"{100 * x:.2f}%"
    c = nums.get("crnn")
    if c:
        out.append(f"CRNN: val CER {p(c['val']['cer'])}, WER {p(c['val']['wer'])} ({c['val']['words']:,} words); "
                   f"test CER {p(c['test']['cer'])}, WER {p(c['test']['wer'])} ({c['test']['words']:,} words); "
                   f"{c['test']['ms_per_word_batched']:.2f} ms/word batched, {c['ms_single_word']:.1f} ms for one word on {c['device']}")
    t = nums.get("tesseract")
    if t:
        parts = [f"{s} CER {p(t[s]['cer'])}, WER {p(t[s]['wer'])} ({t[s]['words']:,} of {t[s]['of_words']:,} words)"
                 for s in ("val", "test") if s in t]
        ms = t.get("test", {}).get("ms_per_word_cpu_core")
        out.append(f"Tesseract {t.get('version', '')} ({t.get('config', '')}): " + "; ".join(parts)
                   + (f"; {ms:.0f} ms/word per CPU core" if ms else ""))
    m = nums.get("model")
    if m:
        out.append(f"Model: {m['parameters']:,} parameters ({m['size_mb_fp32']} MB float32), "
                   f"{m['macs_per_word_w128'] / 1e6:.0f} M MACs per 128-px word, {m['num_classes']} output classes")
    tr = nums.get("training")
    if tr:
        out.append(f"Training: {tr['epochs_run']} epochs run (max {tr['max_epochs']}), best epoch {tr['best_epoch']} "
                   f"(val CER {p(tr['best_val_cer'])}), {tr['train_minutes']:.1f} min on {tr['device']}")
    d = nums.get("data")
    if d:
        sp = d["splits"]
        out.append(f"Data ({d['label_source']}): " + ", ".join(
            f"{s} {sp[s]['words']:,} words / {sp[s]['writers']} writers" for s in ("train", "val", "test"))
            + f"; {d['writers_shared_between_splits']} writers shared between splits")
    sw = nums.get("sweep")
    if isinstance(sw, dict) and sw.get("runs"):
        best = sw["runs"][0]
        out.append(f"Sweep: {len(sw['runs'])} runs ({sw['epochs_per_run']} epochs on {sw['train_frac']:.0%} of train, "
                   f"{sw['total_minutes']:.0f} min total); best {best['name']} val CER {p(best['best_val_cer'])}; "
                   f"chosen: {sw.get('chosen') or 'defaults'}")
    e = nums.get("emnist")
    if e:
        parts = [f"{s} CER {p(e[s]['cer'])}, WER {p(e[s]['wer'])} (case-insensitive CER {p(e[s]['cer_case_insensitive'])}; "
                 f"{e[s]['words']:,} of {e[s]['of_words']:,} words)" for s in ("val", "test") if s in e]
        c = e.get("classifier", {})
        acc = c.get("test", {}).get("accuracy")
        out.append("EMNIST baseline: " + "; ".join(parts)
                   + (f"; classifier EMNIST test accuracy {p(acc)}" if acc is not None else "")
                   + (f"; {e['test']['ms_per_word']:.1f} ms/word" if "test" in e else ""))
    cmp = nums.get("comparison")
    if cmp:
        models = [k for k in cmp if isinstance(cmp[k], dict) and "test" in cmp[k]]
        if models:
            out.append("Comparison (same test words): " + "; ".join(
                f"{k} CER {p(cmp[k]['test']['cer'])} / WER {p(cmp[k]['test']['wer'])}" for k in models))
        if cmp.get("note"):
            out.append("Comparison: " + cmp["note"])
    wc = nums.get("webcam")
    if isinstance(wc, dict) and wc.get("models"):
        out.append(f"Webcam test set ({wc['words']} words): " + "; ".join(
            f"{v['name']} CER {p(v['cer'])} / WER {p(v['wer'])}" for v in wc["models"].values()))
    return out


FUTURE_WORK = {
    "emnist": "EMNIST character-classifier baseline (segment the word into characters, classify each with a CNN "
              "trained on EMNIST): planned second baseline.",
    "augment": "Webcam-style augmentation (blur, perspective, lighting, noise) and the with/without ablation.",
}


def future_work(rep):
    """Future-work items that are still open (EMNIST disappears once Step 4 has run, augmentation once Step 6 has)."""
    done = {"emnist": (rep.dir / "emnist_metrics.json").exists(),
            "augment": (rep.dir.parent / "model_b" / "model_b_metrics.json").exists()}
    return [v for k, v in FUTURE_WORK.items() if not done.get(k)]
